export function pick<T>(xs: T[]): T {
  return xs[Math.floor(Math.random() * xs.length)];
}

export function praiseFor(task: string, custom: string[]): string {
  const pool = [...BUILTIN_PHRASES, ...custom, ...custom];
  return pick(pool).replaceAll('{task}', task);
}
